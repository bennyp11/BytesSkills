 USING(account_id=current_setting('bytes.account_id',true));
CREATE FUNCTION can_access_workspace(w text) RETURNS boolean LANGUAGE sql STABLE SECURITY INVOKER
 SET search_path=bytes,pg_catalog,pg_temp AS $$
 SELECT w=current_setting('bytes.workspace_id',true) AND EXISTS (
  SELECT 1 FROM workspace_memberships m JOIN accounts a ON a.id=m.account_id
  WHERE m.workspace_id=w AND m.account_id=current_setting('bytes.account_id',true)
  AND m.status='active' AND m.role='owner' AND (a.status='active' OR (
   a.id='legacy-owner' AND a.status='unclaimed' AND current_setting('bytes.legacy_owner',true)='true'
  ))
 )
$$;
GRANT EXECUTE ON FUNCTION can_access_workspace(text) TO bytes_runtime;
CREATE POLICY own_workspace ON workspace FOR SELECT TO bytes_runtime USING(can_access_workspace(id));
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['revisions','heads','tags','edges','requests','library_state','library_decisions','workflow_sessions','revision_workflows','search_documents'] LOOP
  EXECUTE format('CREATE POLICY tenant ON bytes.%I TO bytes_runtime USING (bytes.can_access_workspace(workspace_id)) WITH CHECK (bytes.can_access_workspace(workspace_id))',t);
 END LOOP;
END $$;
