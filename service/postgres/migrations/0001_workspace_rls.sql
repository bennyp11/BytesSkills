CREATE FUNCTION immutable() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN RAISE EXCEPTION 'immutable_%',TG_TABLE_NAME; END $$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['revisions','revision_workflows','skill_releases','skill_revocations','library_decisions','workflow_sessions'] LOOP
  EXECUTE format('CREATE TRIGGER immutable BEFORE UPDATE OR DELETE ON bytes.%I FOR EACH ROW EXECUTE FUNCTION bytes.immutable()',t);
