END $$;
CREATE FUNCTION check_revision() RETURNS trigger LANGUAGE plpgsql SET search_path=bytes,pg_catalog,pg_temp AS $$
 DECLARE old heads; previous text;
 BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(NEW.workspace_id,0));
  SELECT * INTO old FROM heads WHERE workspace_id=NEW.workspace_id AND id=NEW.id;
  IF NEW.revision<>coalesce(old.revision+1,1) THEN RAISE EXCEPTION 'revision_conflict'; END IF;
  SELECT checksum INTO previous FROM revisions WHERE workspace_id=NEW.workspace_id AND pointer=old.pointer;
  IF NEW.revision>1 AND ((NEW.record::jsonb->>'previous_checksum') IS DISTINCT FROM previous OR NEW.type<>old.type)
    THEN RAISE EXCEPTION 'revision_conflict'; END IF;
  RETURN NEW;
 END $$;
CREATE TRIGGER revision_sequence BEFORE INSERT ON revisions FOR EACH ROW EXECUTE FUNCTION check_revision();
CREATE FUNCTION check_head() RETURNS trigger LANGUAGE plpgsql SET search_path=bytes,pg_catalog,pg_temp AS $$
 BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(NEW.workspace_id,0));
  IF TG_OP='UPDATE' AND (NEW.workspace_id<>OLD.workspace_id OR NEW.id<>OLD.id) THEN RAISE EXCEPTION 'immutable_identity'; END IF;
  IF NEW.parent IS NOT NULL THEN
   IF NEW.type<>'concept' OR NEW.parent=NEW.id OR NOT EXISTS (
    SELECT 1 FROM heads WHERE workspace_id=NEW.workspace_id AND id=NEW.parent AND type='concept'
   ) THEN RAISE EXCEPTION 'invalid_parent'; END IF;
   IF EXISTS(WITH RECURSIVE ancestors(id,parent) AS (
    SELECT id,parent FROM heads WHERE workspace_id=NEW.workspace_id AND id=NEW.parent UNION
    SELECT h.id,h.parent FROM heads h JOIN ancestors a ON h.id=a.parent WHERE h.workspace_id=NEW.workspace_id
   ) SELECT 1 FROM ancestors WHERE id=NEW.id) THEN RAISE EXCEPTION 'parent_cycle'; END IF;
  END IF;
  RETURN NEW;
 END $$;
CREATE TRIGGER head_integrity BEFORE INSERT OR UPDATE ON heads FOR EACH ROW EXECUTE FUNCTION check_head();
CREATE FUNCTION check_state() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN
  IF NEW.workspace_id<>OLD.workspace_id OR NEW.revision<>OLD.revision+1 THEN RAISE EXCEPTION 'adoption_conflict'; END IF;
  RETURN NEW;
 END $$;
CREATE TRIGGER state_cas BEFORE UPDATE ON library_state FOR EACH ROW EXECUTE FUNCTION check_state();
CREATE FUNCTION initialize_library() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=bytes,pg_catalog,pg_temp AS $$
 BEGIN INSERT INTO library_state VALUES(NEW.id,0,'{}','{}','{}'); RETURN NEW; END $$;
CREATE TRIGGER initialize_workspace AFTER INSERT ON workspace FOR EACH ROW EXECUTE FUNCTION initialize_library();
-- Publisher can invalidate previews, but cannot read or write workspace content.
CREATE FUNCTION invalidate_previews() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=bytes,pg_catalog,pg_temp AS $$
 BEGIN UPDATE library_state SET revision=revision+1; RETURN NEW; END $$;
CREATE TRIGGER release_preview AFTER INSERT ON skill_releases FOR EACH ROW EXECUTE FUNCTION invalidate_previews();
CREATE TRIGGER revocation_preview AFTER INSERT ON skill_revocations FOR EACH ROW EXECUTE FUNCTION invalidate_previews();
CREATE FUNCTION check_release() RETURNS trigger LANGUAGE plpgsql SET search_path=bytes,pg_catalog,pg_temp AS $$
 BEGIN
  PERFORM pg_advisory_xact_lock(17491,1);
  IF NEW.sequence<>coalesce((SELECT max(sequence)+1 FROM skill_releases WHERE skill=NEW.skill),1) THEN RAISE EXCEPTION 'release_conflict'; END IF;
  RETURN NEW;
 END $$;
CREATE TRIGGER release_sequence BEFORE INSERT ON skill_releases FOR EACH ROW EXECUTE FUNCTION check_release();

-- Only the trusted identity adapter receives this separate credential. No email
-- matching, arbitrary workspace claims, reassignment or legacy-owner auto-claim.
CREATE FUNCTION provision_identity(iss text,sub text,new_account text,new_workspace text)
 RETURNS TABLE(account_id text,workspace_id text) LANGUAGE plpgsql SECURITY DEFINER SET search_path=bytes,pg_catalog,pg_temp AS $$
 DECLARE found_account text; matches integer;
 BEGIN
  IF iss NOT LIKE 'https://%' OR length(iss)>2048 OR length(sub) NOT BETWEEN 1 AND 512 THEN RAISE EXCEPTION 'invalid_identity'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(iss || chr(10) || sub,1));
  SELECT i.account_id INTO found_account FROM account_identities i WHERE i.issuer=iss AND i.subject=sub;
  IF found_account IS NULL THEN
   INSERT INTO accounts(id,status) VALUES(new_account,'active');
   INSERT INTO workspace VALUES(new_workspace,'My workspace');
   INSERT INTO workspace_memberships(workspace_id,account_id,role,status) VALUES(new_workspace,new_account,'owner','active');
   INSERT INTO account_identities(issuer,subject,account_id) VALUES(iss,sub,new_account);
   found_account:=new_account;
  END IF;
  SELECT count(*) INTO matches FROM accounts a JOIN workspace_memberships m ON m.account_id=a.id
   WHERE a.id=found_account AND a.status='active' AND m.status='active' AND m.role='owner';
  IF matches<>1 THEN RAISE EXCEPTION 'account_unavailable'; END IF;
  RETURN QUERY SELECT a.id,m.workspace_id FROM accounts a JOIN workspace_memberships m ON m.account_id=a.id
   WHERE a.id=found_account AND a.status='active' AND m.status='active' AND m.role='owner';
 END $$;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA bytes FROM PUBLIC;
GRANT EXECUTE ON FUNCTION provision_identity(text,text,text,text) TO bytes_identity;
