-- Run once using a separate schema administrator, never the Worker credential.
-- Credential passwords are provisioned out of band; these roles cannot log in yet.
CREATE ROLE bytes_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
CREATE ROLE bytes_publisher NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
CREATE ROLE bytes_identity NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
CREATE SCHEMA bytes;
REVOKE ALL ON SCHEMA bytes FROM PUBLIC;
GRANT USAGE ON SCHEMA bytes TO bytes_runtime,bytes_publisher,bytes_identity;
SET LOCAL search_path = bytes,pg_catalog;
ALTER DEFAULT PRIVILEGES IN SCHEMA bytes REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

CREATE TABLE accounts (
 id text PRIMARY KEY, status text NOT NULL CHECK(status IN ('unclaimed','active','disabled')),
 created_at text NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE TABLE workspace (id text PRIMARY KEY, name text NOT NULL);
CREATE TABLE account_identities (
 issuer text NOT NULL CHECK(length(issuer)>0),subject text NOT NULL CHECK(length(subject)>0),
 account_id text NOT NULL REFERENCES accounts(id),
 created_at text NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
 PRIMARY KEY(issuer,subject)
);
CREATE INDEX account_identities_account ON account_identities(account_id);
CREATE TABLE workspace_memberships (
 workspace_id text NOT NULL REFERENCES workspace(id),account_id text NOT NULL REFERENCES accounts(id),
 role text NOT NULL CHECK(role='owner'),status text NOT NULL CHECK(status IN ('active','revoked')),
 created_at text NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
 PRIMARY KEY(workspace_id,account_id)
);
CREATE UNIQUE INDEX workspace_active_owner ON workspace_memberships(workspace_id) WHERE status='active';
CREATE INDEX memberships_account ON workspace_memberships(account_id,status,workspace_id);
CREATE TABLE skill_releases (
 skill text NOT NULL,version text NOT NULL,sequence integer NOT NULL CHECK(sequence>0),
 checksum text NOT NULL,payload text NOT NULL CHECK(jsonb_typeof(payload::jsonb)='object'),published_at text NOT NULL,
 PRIMARY KEY(skill,version),UNIQUE(skill,sequence)
);
CREATE TABLE skill_revocations (
 skill text NOT NULL,version text NOT NULL,reason text NOT NULL,PRIMARY KEY(skill,version),
 FOREIGN KEY(skill,version) REFERENCES skill_releases(skill,version)
);
CREATE TABLE revisions (
 workspace_id text NOT NULL REFERENCES workspace(id),pointer text NOT NULL,id text NOT NULL,
 type text NOT NULL CHECK(type IN ('concept','hook','script','plan','video','image','audio','run','brief')),
 revision integer NOT NULL CHECK(revision>=1),checksum text NOT NULL,record text NOT NULL,
 -- Keep original canonical JSON bytes: jsonb storage would change checksums.
 CHECK((record::jsonb->>'workspace_id') IS NOT DISTINCT FROM workspace_id),
 CHECK((record::jsonb->>'id') IS NOT DISTINCT FROM id AND (record::jsonb->>'pointer') IS NOT DISTINCT FROM pointer),
 CHECK((record::jsonb->>'type') IS NOT DISTINCT FROM type AND (record::jsonb->>'revision')::integer IS NOT DISTINCT FROM revision),
 rowid integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 PRIMARY KEY(workspace_id,pointer),UNIQUE(workspace_id,id,revision),UNIQUE(workspace_id,pointer,id,type,revision)
);
CREATE TABLE heads (
 workspace_id text NOT NULL REFERENCES workspace(id),id text NOT NULL,pointer text NOT NULL,type text NOT NULL,
 revision integer NOT NULL,title text NOT NULL,status text NOT NULL,format text,parent text,updated text NOT NULL,
 PRIMARY KEY(workspace_id,id),
 FOREIGN KEY(workspace_id,pointer,id,type,revision) REFERENCES revisions(workspace_id,pointer,id,type,revision) DEFERRABLE INITIALLY DEFERRED,
 FOREIGN KEY(workspace_id,parent) REFERENCES heads(workspace_id,id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX tenant_heads_filter ON heads(workspace_id,type,status,format,id);
CREATE INDEX tenant_heads_parent ON heads(workspace_id,parent,id);
CREATE TABLE tags (
 workspace_id text NOT NULL,id text NOT NULL,tag text NOT NULL,PRIMARY KEY(workspace_id,id,tag),
 FOREIGN KEY(workspace_id,id) REFERENCES heads(workspace_id,id)
);
CREATE INDEX tenant_tags_lookup ON tags(workspace_id,tag,id);
CREATE TABLE edges (
 workspace_id text NOT NULL,source text NOT NULL,kind text NOT NULL CHECK(kind IN ('inputs','derived_from','links','outputs')),
 target text NOT NULL,PRIMARY KEY(workspace_id,source,kind,target),
 FOREIGN KEY(workspace_id,source) REFERENCES revisions(workspace_id,pointer) DEFERRABLE INITIALLY DEFERRED,
 FOREIGN KEY(workspace_id,target) REFERENCES revisions(workspace_id,pointer) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX tenant_edges_reverse ON edges(workspace_id,target,kind,source);
CREATE TABLE requests (
 workspace_id text NOT NULL,request_id text NOT NULL,fingerprint text NOT NULL,pointer text NOT NULL,created_at text NOT NULL,
 PRIMARY KEY(workspace_id,request_id),
 FOREIGN KEY(workspace_id,pointer) REFERENCES revisions(workspace_id,pointer) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE library_state (
 workspace_id text PRIMARY KEY REFERENCES workspace(id),revision integer NOT NULL,
 selections text NOT NULL CHECK(jsonb_typeof(selections::jsonb)='object'),
 policies text NOT NULL CHECK(jsonb_typeof(policies::jsonb)='object'),dismissed text NOT NULL CHECK(jsonb_typeof(dismissed::jsonb)='object')
);
CREATE TABLE library_decisions (
 workspace_id text NOT NULL REFERENCES workspace(id),request_id text NOT NULL,fingerprint text NOT NULL,
 result text NOT NULL CHECK(jsonb_typeof(result::jsonb)='object'),created_at text NOT NULL,PRIMARY KEY(workspace_id,request_id)
);
CREATE TABLE workflow_sessions (
 workspace_id text NOT NULL REFERENCES workspace(id),id text NOT NULL,fingerprint text NOT NULL,skill text NOT NULL,
 version text NOT NULL,command text NOT NULL,created_at text NOT NULL,expires_at text NOT NULL,
 PRIMARY KEY(workspace_id,id),FOREIGN KEY(skill,version) REFERENCES skill_releases(skill,version)
);
CREATE TABLE revision_workflows (
 workspace_id text NOT NULL,pointer text NOT NULL,workflow_id text NOT NULL,PRIMARY KEY(workspace_id,pointer),
 FOREIGN KEY(workspace_id,pointer) REFERENCES revisions(workspace_id,pointer) DEFERRABLE INITIALLY DEFERRED,
 FOREIGN KEY(workspace_id,workflow_id) REFERENCES workflow_sessions(workspace_id,id)
);
CREATE TABLE search_documents (
 workspace_id text NOT NULL,id text NOT NULL,title text NOT NULL,body text NOT NULL,
 document tsvector GENERATED ALWAYS AS (to_tsvector('simple',title || ' ' || body)) STORED,
 PRIMARY KEY(workspace_id,id),FOREIGN KEY(workspace_id,id) REFERENCES heads(workspace_id,id)
);
CREATE INDEX tenant_search_document ON search_documents USING gin(document);

